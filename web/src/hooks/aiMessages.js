// ============================================================
//  hooks/aiMessages.js —— AI 接口的状态码 → 人话
//
//  ⭐ 为什么单独一个文件？
//
//     useAiParse 和 useAgent 打的是两个不同的接口，
//     但它们【失败的方式是同一批】：
//     422 / 502 / 503 / 504，含义完全一样。
//
//     而且"给用户看什么"这个决定，应该只有一份。
//     复制一遍到另一个 hook 里，将来改文案就要改两处，
//     漏一处就变成"同一个错误，两个页面说两套话"。
//
//  ⚠️ 判据始终是：用户看了这句话，能做什么？
//      422 → 他能改输入
//      502 → 他能换个说法
//      503/504 → 他只能等一会儿
// ============================================================

export const STATUS_MESSAGE = {
    422: "输入不合法（可能太长，或者全是空格）",
    502: "AI 没能给出有效结果，换个说法再试一次",
    503: "AI 服务暂时不可用，请稍后再试",
    504: "AI 想太久了，请稍后再试",
};

// fetch 本身失败（后端没启动 / 网络断）时，err 是 TypeError 而没有中文 message。
// 这个判断两个 hook 都要用，同样只写一份。
export function friendlyError(err) {
    return err instanceof TypeError
        ? "连不上后端，请确认 uvicorn 已启动"
        : err.message;
}
